def code_units(value):
    raw = value.encode('utf-16-le', errors='surrogatepass')
    return [int.from_bytes(raw[n:n + 2], 'little') for n in range(0, len(raw), 2)]


def clone_graph(graph):
    result = copy.copy(graph)
    for name in ('nodes', 'locals', 'edges', 'audit'):
        setattr(result, name, copy.deepcopy(getattr(graph, name)))
    return result


class BreakLoop(Exception):
    pass


class Returned(Exception):
    pass


class GraphMachine:
    def __init__(self, graph, inputs):
        self.g, self.inputs = graph, inputs
        self.locals = {name: {'bool': False, 'int': 0, 'string': ''}[data['kind']] for name, data in graph.locals.items()}
        self.incoming = {(b, pb): (a, pa) for a, pa, b, pb in graph.edges
                         if graph.nodes[a]['pins'][pa]['PinType.PinCategory'] != '"exec"'}
        self.outgoing = {(a, pa): (b, pb) for a, pa, b, pb in graph.edges
                         if graph.nodes[a]['pins'][pa]['PinType.PinCategory'] == '"exec"'}
        self.indices, self.steps, self.char_reads, self.substrings = {}, 0, [], []

    def input(self, name, pin):
        if (name, pin) in self.incoming:
            return self.value(*self.incoming[name, pin])
        p = self.g.nodes[name]['pins'][pin]
        kind = json.loads(p['PinType.PinCategory'])
        default = json.loads(p.get('DefaultValue', p.get('AutogeneratedDefaultValue', '""')))
        if kind == 'bool':
            return default.lower() == 'true'
        if kind == 'int':
            return int(default or 0)
        if kind == 'string':
            return default
        raise AssertionError('Unmodeled input: ' + kind)

    def variable(self, name):
        fields = self.g.nodes[name]['fields']
        ref = next(f for f in fields if f.startswith('VariableReference='))
        return re.search(r'MemberName="([^"]+)"', ref).group(1)

    def value(self, name, pin):
        node = self.g.nodes[name]
        if name == 'Entry':
            return self.inputs[pin]
        if node['class'].endswith('K2Node_VariableGet') or node['class'].endswith('K2Node_VariableSet'):
            return self.locals[self.variable(name)]
        if node['class'].endswith('K2Node_MacroInstance'):
            return self.indices[name]
        ref = next(f for f in node['fields'] if f.startswith('FunctionReference='))
        function = re.search(r'MemberName="([^"]+)"', ref).group(1)
        inp = lambda port: self.input(name, port)
        if function in ('Add_IntInt', 'Subtract_IntInt', 'Less_IntInt', 'LessEqual_IntInt',
                        'EqualEqual_IntInt', 'BooleanAND', 'BooleanOR', 'Concat_StrStr'):
            a, b = inp('A'), inp('B')
            ops = {'Add_IntInt': lambda: a + b, 'Subtract_IntInt': lambda: a - b,
                   'Less_IntInt': lambda: a < b, 'LessEqual_IntInt': lambda: a <= b,
                   'EqualEqual_IntInt': lambda: a == b, 'BooleanAND': lambda: a and b,
                   'BooleanOR': lambda: a or b, 'Concat_StrStr': lambda: a + b}
            return ops[function]()
        if function == 'Not_PreBool':
            return not inp('A')
        if function == 'Len':
            return len(code_units(inp('S')))
        if function == 'GetCharacterAsNumber':
            source, index = code_units(inp('SourceString')), inp('Index')
            if not 0 <= index < len(source):
                raise AssertionError('Out-of-range character read')
            self.char_reads.append((name, index))
            return source[index]
        if function == 'GetSubstring':
            source, start, length = code_units(inp('SourceString')), inp('StartIndex'), inp('Length')
            if not 0 <= start <= len(source) or not 0 < length <= 40 or start + length > len(source):
                raise AssertionError('Unbounded or out-of-range substring')
            self.substrings.append((start, length))
            raw = b''.join(x.to_bytes(2, 'little') for x in source[start:start + length])
            return raw.decode('utf-16-le', errors='surrogatepass')
        raise AssertionError('Unmodeled source function: ' + function)

    def follow(self, name, pin):
        target = self.outgoing.get((name, pin))
        if target:
            self.execute(*target)

    def execute(self, name, input_pin):
        self.steps += 1
        if self.steps > 10000:
            raise AssertionError('Graph execution exceeded fixed test bound')
        node = self.g.nodes[name]
        if name == 'Return':
            raise Returned({pin: self.input(name, pin) for pin in node['pins'] if pin != 'execute'})
        if node['class'].endswith('K2Node_IfThenElse'):
            return self.follow(name, 'then' if self.input(name, 'Condition') else 'else')
        if node['class'].endswith('K2Node_VariableSet'):
            variable = self.variable(name)
            self.locals[variable] = self.input(name, variable)
            return self.follow(name, 'then')
        if node['class'].endswith('K2Node_MacroInstance'):
            if input_pin == 'Break':
                raise BreakLoop(name)
            if input_pin != 'Execute':
                raise AssertionError('Unknown loop input')
            for index in range(self.input(name, 'FirstIndex'), self.input(name, 'LastIndex') + 1):
                self.indices[name] = index
                try:
                    self.follow(name, 'LoopBody')
                except BreakLoop as e:
                    if e.args != (name,):
                        raise
                    break
            return self.follow(name, 'Completed')
        raise AssertionError('Unmodeled execution node: ' + name)

    def run(self):
        try:
            self.follow('Entry', 'then')
        except Returned as e:
            return e.args[0]
        raise AssertionError('Graph did not return')


class TextFunctions(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.templates = build.core.Templates()
        cls.validator = build.validate_function(cls.templates)
        cls.segmenter = build.segment_function(cls.templates)

    def validation(self, raw, limit=256):
        machine = GraphMachine(self.validator, {'Raw': raw, 'Limit': limit})
        return machine.run(), machine

    def segmentation(self, raw):
        machine = GraphMachine(self.segmenter, {'Raw': raw})
        return machine.run(), machine

    def test_valid_ascii_and_unicode_lengths(self):
        for raw in ['a', '/Game/Objects/Controller_C_0', '界' * 128, '🚀' * 128, 'W' * 256]:
            with self.subTest(raw=raw[:20]):
                result, machine = self.validation(raw)
                self.assertEqual(result, {'Valid': True, 'Units': len(code_units(raw))})
                self.assertEqual(len(machine.char_reads), result['Units'])

    def test_limit_empty_and_huge_input_fail_before_character_read(self):
        for raw, limit in [('', 256), ('a', 0), ('a', -1), ('a', 257), ('a', 2147483647),
                           ('x' * 129, 128), ('x' * 257, 256), ('x' * 100000, 256)]:
            with self.subTest(length=len(raw), limit=limit):
                result, machine = self.validation(raw, limit)
                self.assertFalse(result['Valid'])
                self.assertEqual(result['Units'], len(code_units(raw)))
                self.assertEqual(machine.char_reads, [])

    def test_all_control_codes_rejected(self):
        for number in list(range(32)) + [127]:
            result, _ = self.validation('prefix' + chr(number) + 'suffix')
            self.assertFalse(result['Valid'], number)

    def test_surrogate_boundary_values(self):
        valid = ['\ud800\udc00', '\udbff\udfff', 'a\ud800\udfffz', '\ud7ff', '\ue000']
        invalid = ['\ud800', '\udbff', '\udc00', '\udfff', '\ud800a', '\ud800\ud800',
                   '\udc00\ud800', '\udbff\x00', 'x' * 255 + '\ud800']
        for raw in valid:
            self.assertTrue(self.validation(raw)[0]['Valid'])
        for raw in invalid:
            self.assertFalse(self.validation(raw)[0]['Valid'])

    def test_invalid_surrogate_stops_bounded_scan(self):
        result, machine = self.validation('x\udc00' + 'z' * 254)
        self.assertFalse(result['Valid'])
        self.assertEqual(len(machine.char_reads), 2)

    def test_segment_width_exact_boundaries_and_reconstruction(self):
        for raw in ['x', 'W' * 39, 'W' * 40, 'W' * 41, '界' * 256, 'W' * 256,
                    'a' * 39 + '🚀' + 'b' * 80, 'a' * 38 + '🚀' + 'b' * 80,
                    '🚀' * 128, 'a' * 255 + 'z']:
            with self.subTest(length=len(code_units(raw))):
                result, machine = self.segmentation(raw)
                self.assertTrue(result['Valid'])
                rows = result['Segmented'].split('\n')
                self.assertEqual(''.join(rows), raw)
                self.assertEqual(result['Lines'], len(rows))
                self.assertLessEqual(len(rows), 7)
                self.assertTrue(all(1 <= len(code_units(row)) <= 40 for row in rows))
                self.assertTrue(all(not 55296 <= code_units(row)[-1] <= 56319 for row in rows))
                self.assertLessEqual(len(machine.substrings), 7)

    def test_segmenter_rejects_invalid_input_without_substring(self):
        for raw in ['', 'x' * 257, 'a\n', '\x00', '\ud800', '\udc00', 'a\ud800b']:
            result, machine = self.segmentation(raw)
            self.assertEqual(result, {'Valid': False, 'Segmented': '', 'Lines': 0})
            self.assertEqual(machine.substrings, [])

    def test_segment_surrogate_at_every_possible_boundary(self):
        for position in range(255):
            raw = 'a' * position + '🚀' + 'b' * (254 - position)
            result, _ = self.segmentation(raw)
            self.assertTrue(result['Valid'], position)
            self.assertEqual(result['Segmented'].replace('\n', ''), raw)
            for row in result['Segmented'].split('\n'):
                self.assertLessEqual(len(code_units(row)), 40)
                self.assertFalse(55296 <= code_units(row)[-1] <= 56319)

    def test_deterministic_mixed_unicode_examples(self):
        rng = random.Random(27092026)
        alphabet = ['a', '/', '界', 'Ж', 'é', '🚀', '🛰']
        for unused in range(80):
            raw = ''.join(rng.choice(alphabet) for x in range(rng.randint(1, 150)))
            if len(code_units(raw)) > 256:
                continue
            result, _ = self.segmentation(raw)
            self.assertTrue(result['Valid'])
            self.assertEqual(result['Segmented'].replace('\n', ''), raw)

    def test_local_state_resets_per_call(self):
        self.assertFalse(self.validation('\ud800')[0]['Valid'])
        self.assertTrue(self.validation('next')[0]['Valid'])
        self.assertEqual(self.segmentation('next')[0]['Segmented'], 'next')

    def test_fixed_loop_limits_and_character_input_bound(self):
        for graph in [self.validator, self.segmenter]:
            self.assertEqual(json.loads(graph.nodes['ValidationLoop']['pins']['LastIndex']['DefaultValue']), '255')
            self.assertEqual(json.loads(graph.nodes['ValidationLoop']['pins']['FirstIndex']['DefaultValue']), '0')
        self.assertEqual(json.loads(self.segmenter.nodes['SegmentLoop']['pins']['LastIndex']['DefaultValue']), '6')
        result, machine = self.segmentation('W' * 256)
        self.assertTrue(result['Valid'])
        self.assertLessEqual(len(machine.char_reads), 262)

    def test_payload_exact_json_envelope_reciprocal_internal_links(self):
        for graph in [self.validator, self.segmenter]:
            payload = graph.emit().decode('utf-8')
            prefix, quoted = payload.split('NodesString=', 1)
            body, end = json.JSONDecoder().raw_decode(quoted)
            self.assertEqual(quoted[end:], ')')
            self.assertEqual(prefix + 'NodesString=' + json.dumps(body, ensure_ascii=False) + ')', payload)
            self.assertIn('GraphName="' + graph.function + '"', prefix)
            nodes = []
            for match in re.finditer(r'Begin Object Class=([^ ]+) Name="([^"]+)"\r\n(.*?)\r\nEnd Object', body, re.S):
                lines = [x.strip() for x in match.group(3).split('\r\n')]
                nodes.append({'relative_path': match.group(2), 'pin_lines': [{'text': x} for x in lines if x.startswith('CustomProperties Pin (')]})
            self.assertEqual(len(nodes), len(graph.nodes))
            pins, edges, removed = graph.h['checked_graph'](nodes)
            self.assertEqual(removed, [])
            self.assertEqual(len(edges), len(graph.edges) * 2)
            self.assertEqual(len(pins), graph.validate()['pin_count'])

    def test_generated_scoped_locals_match_declarations(self):
        for graph in [self.validator, self.segmenter]:
            graph.validate()
            for name, local in graph.locals.items():
                self.assertIn('VarName="' + name + '"', local['declaration'])
                self.assertIn('VarGuid=' + local['guid'], local['declaration'])
                self.assertIn('VarType=(PinCategory="' + local['kind'] + '")', local['declaration'])

    def test_rebuild_has_disjoint_generated_ids(self):
        other = build.validate_function(self.templates)
        self.assertFalse(set(other.validate()['ids']) & set(self.validator.validate()['ids']))

    def test_foreign_local_binding_fails_closed(self):
        graph = clone_graph(self.validator)
        node = graph.nodes['StoreUnits']
        node['fields'] = [x.replace('MemberScope="ValidateBoundedIdentity"', 'MemberScope="Other"') for x in node['fields']]
        with self.assertRaisesRegex(ValueError, 'FOREIGN_OR_UNDECLARED_LOCAL_REFERENCE'):
            graph.emit()

    def test_local_type_or_id_corruption_fails_closed(self):
        graph = clone_graph(self.validator)
        graph.nodes['StoreUnits']['pins']['VUnits']['PinType.PinCategory'] = '"string"'
        with self.assertRaisesRegex(ValueError, 'LOCAL_PIN_DECLARATION_TYPE'):
            graph.emit()
        graph = clone_graph(self.validator)
        graph.nodes['StoreUnits']['guid'] = graph.nodes['Entry']['guid']
        with self.assertRaisesRegex(ValueError, 'GENERATED_ID_COLLISION'):
            graph.emit()

    def test_wrong_link_type_and_multiple_exec_fanout_rejected(self):
        graph = clone_graph(self.validator)
        with self.assertRaisesRegex(ValueError, 'LINK_TYPE'):
            graph.connect('Entry', 'Raw', 'Return', 'Units')
        with self.assertRaisesRegex(ValueError, 'EXEC_OUTPUT_FANOUT'):
            graph.connect('Entry', 'then', 'Return', 'execute')

    def test_no_unobserved_bool_input_template_is_fabricated(self):
        with self.assertRaisesRegex(ValueError, 'UNOBSERVED_SIGNATURE_TYPE'):
            self.templates.scalar_port('bool', 'input')

    def test_no_gameplay_or_assets_in_graph_functions(self):
        allowed = {'Len', 'GetCharacterAsNumber', 'LessEqual_IntInt', 'Less_IntInt',
                   'EqualEqual_IntInt', 'BooleanAND', 'BooleanOR', 'Not_PreBool',
                   'Add_IntInt', 'Subtract_IntInt', 'Concat_StrStr', 'GetSubstring'}
        for graph in [self.validator, self.segmenter]:
            for name, node in graph.nodes.items():
                if name in ('Entry', 'Return'):
                    continue
                for field in node['fields']:
                    if field.startswith('FunctionReference='):
                        called = re.search(r'MemberName="([^"]+)"', field).group(1)
                        self.assertIn(called, allowed)

    def test_frozen_exact_candidate_graphs_execute_contract(self):
        directory = ROOT / 'research/evidence/phase-b-text-functions-20260927-01'
        for name, sha in [('ValidateBoundedIdentity', 'c8a5a7adf103b9dc1c1a304711134ac27d933e624f7778fed86211ad857a12e4'),
                          ('SegmentValidatedPath', '7afa3be0e60cda0affb0b7f0f56902601d8d8ce7d64521f72bd571c0946c44cf')]:
            raw = (directory / (name + '.graph.json')).read_bytes()
            self.assertEqual(build.core.digest(raw), sha)
            data = json.loads(raw)
            graph = copy.copy(self.validator if name == 'ValidateBoundedIdentity' else self.segmenter)
            graph.nodes = {n['label']: n for n in data['nodes']}
            graph.locals, graph.edges = data['locals'], [tuple(e) for e in data['edges']]
            for text, valid in [('', False), ('ok', True), ('x' * 257, False), ('x\n', False),
                                ('\ud800', False), ('a' * 39 + '🚀' + '界' * 90, True), ('🚀' * 128, True)]:
                inputs = {'Raw': text, 'Limit': 256} if name == 'ValidateBoundedIdentity' else {'Raw': text}
                result = GraphMachine(graph, inputs).run()
                self.assertEqual(result['Valid'], valid)
                if valid and name == 'SegmentValidatedPath':
                    self.assertEqual(result['Segmented'].replace('\n', ''), text)

    def test_sources_parse_under_python37_grammar(self):
        for file in [build.CORE_PATH, Path(build.__file__), Path(__file__)]:
            ast.parse(file.read_text(encoding='utf-8-sig'), filename=str(file), feature_version=(3, 7))


