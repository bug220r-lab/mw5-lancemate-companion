def function(node):
    field = next(f for f in node['fields'] if f.startswith('FunctionReference='))
    return re.search(r'MemberName="([^"]+)"', field).group(1)


def oracle(name, inputs):
    if name == 'ValidateBoundedIdentity':
        length = len(inputs['Raw'].encode('utf-16-le')) // 2
        try:
            model.checked_identity(inputs['Raw'], inputs['Limit'])
            valid = True
        except model.BoundError:
            valid = False
        return {'Valid': valid, 'Units': length}
    if name == 'SegmentValidatedPath':
        try:
            lines = model.path_segments(inputs['Raw'])
            return {'Valid': True, 'Segmented': '\n'.join(lines), 'Lines': len(lines)}
        except model.BoundError:
            return {'Valid': False, 'Segmented': '', 'Lines': 0}
    if name == 'DecorateBoundedPage':
        try:
            page = model.decorate(inputs['Body'], inputs['Index'], inputs['Total'], inputs['Status'])
            return {'Valid': True, 'Page': page, 'Units': model.units(page)}
        except model.BoundError:
            return {'Valid': False, 'Page': '', 'Units': 0}
    raise AssertionError('Unreviewed helper')


class DriverMachine:
    """Only the frozen graph's finite control and comparisons, with mock callees."""
    def __init__(self, graph, fault=None):
        self.g, self.fault = graph, fault
        self.data = {(b, pb): (a, pa) for a, pa, b, pb in graph.edges
                     if graph.nodes[a]['pins'][pa]['PinType.PinCategory'] != '"exec"'}
        self.execs = {(a, pa): (b, pb) for a, pa, b, pb in graph.edges
                      if graph.nodes[a]['pins'][pa]['PinType.PinCategory'] == '"exec"'}
        self.values, self.calls, self.messages, self.steps = {}, [], [], 0

    def input(self, node, pin):
        if (node, pin) in self.data:
            return self.value(*self.data[node, pin])
        p = self.g.nodes[node]['pins'][pin]
        kind = json.loads(p['PinType.PinCategory'])
        value = json.loads(p.get('DefaultValue', p.get('AutogeneratedDefaultValue', '""')))
        if kind == 'bool':
            return value.lower() == 'true'
        if kind == 'int':
            return int(value or 0)
        if kind == 'string':
            return value
        raise AssertionError('Unexpected input kind')

    def value(self, node, pin):
        n = self.g.nodes[node]
        name = function(n)
        if name in build.TARGETS:
            return self.values[node, pin]  # Must already have executed once.
        a = self.input(node, 'A')
        if name == 'Not_PreBool':
            return not a
        b = self.input(node, 'B')
        if name in ('EqualEqual_IntInt', 'EqualEqual_StrStr'):
            return a == b
        if name == 'BooleanAND':
            return a and b
        raise AssertionError('Unreviewed pure function')

    def run(self):
        current = self.execs['Entry', 'then']
        while current is not None:
            self.steps += 1
            if self.steps > 64:
                raise AssertionError('Finite fixture bound exceeded')
            label, pin = current
            n = self.g.nodes[label]
            if n['class'].endswith('.K2Node_IfThenElse'):
                out = 'then' if self.input(label, 'Condition') else 'else'
            else:
                name = function(n)
                if name == 'PrintString':
                    assert self.input(label, 'bPrintToLog') is True
                    assert self.input(label, 'bPrintToScreen') is False
                    self.messages.append(self.input(label, 'InString'))
                elif name in build.TARGETS:
                    if label in self.calls:
                        raise AssertionError('Repeated helper call')
                    self.calls.append(label)
                    inputs = {p: self.input(label, p) for p, metadata in n['pins'].items()
                              if p not in ('execute', 'self') and metadata.get('Direction') != '"EGPD_Output"'}
                    outputs = oracle(name, inputs)
                    if self.fault and self.fault[0] == label:
                        value = outputs[self.fault[1]]
                        outputs[self.fault[1]] = (not value) if type(value) is bool else value + 1 if type(value) is int else value + '!'
                    self.values.update({(label, p): value for p, value in outputs.items()})
                else:
                    raise AssertionError('Unreviewed impure call')
                out = 'then'
            current = self.execs.get((label, out))
        return self


class Tests(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        saved = json.loads((EVIDENCE / (build.FUNCTION + '.graph.json')).read_bytes())
        cls.g = build.core.FunctionGraph(build.core.Templates(), build.FUNCTION)
        cls.g.nodes = {n['label']: n for n in saved['nodes']}
        cls.g.edges = [tuple(e) for e in saved['edges']]
        cls.g.locals, cls.g.audit = saved['locals'], saved['assembly']
        cls.fixtures = build.fixture_data()['fixtures']
        cls.marker = build.fixture_data()['log_marker']

    def test_expected_fixtures_match_independent_model(self):
        for case in self.fixtures:
            with self.subTest(case=case['case_id']):
                self.assertEqual(oracle(case['function'], case['inputs']), case['expected'])

    def test_success_executes_six_once_and_eight_ordered_messages(self):
        run = DriverMachine(self.g).run()
        self.assertEqual(run.calls, ['Case%02dCall' % i for i in range(1, 7)])
        self.assertEqual(run.messages, [self.marker + ' ' + s for s in ['BEGIN'] + ['PASS%02d' % i for i in range(1, 7)] + ['END PASS']])

    def test_each_of_sixteen_wrong_outputs_stops_at_its_case(self):
        checked = 0
        for case in self.fixtures:
            i = case['case_id']
            for output in case['expected']:
                with self.subTest(case=i, output=output):
                    run = DriverMachine(self.g, ('Case%02dCall' % i, output)).run()
                    self.assertEqual(run.calls, ['Case%02dCall' % j for j in range(1, i + 1)])
                    self.assertEqual(run.messages, [self.marker + ' ' + s for s in ['BEGIN'] + ['PASS%02d' % j for j in range(1, i)] + ['FAIL%02d' % i, 'END FAIL']])
                    checked += 1
        self.assertEqual(checked, 16)

    def test_all_exec_paths_terminate_and_all_nodes_are_used(self):
        m = DriverMachine(self.g)
        visited, paths = set(), []
        def data_visit(label):
            visited.add(label)
            for destination, source in m.data.items():
                if destination[0] == label:
                    data_visit(source[0])
        def walk(label, active, calls, prints):
            self.assertNotIn(label, active)
            data_visit(label)
            n = self.g.nodes[label]
            calls = calls + ([label] if label.endswith('Call') else [])
            prints = prints + ([label] if label not in ('Entry',) and not n['class'].endswith('.K2Node_IfThenElse') and function(n) == 'PrintString' else [])
            out = [pair[0] for source, pair in m.execs.items() if source[0] == label]
            if not out:
                self.assertIn(label, ('EndPass', 'EndFail'))
                self.assertLessEqual(len(calls), 6)
                self.assertLessEqual(len(prints), 8)
                self.assertEqual(len(calls), len(set(calls)))
                paths.append(label)
            for target in out:
                walk(target, active | {label}, calls, prints)
        walk('Entry', set(), [], [])
        self.assertEqual((paths.count('EndPass'), paths.count('EndFail')), (1, 6))
        self.assertEqual(visited, set(self.g.nodes))

    def test_metadata_boundary_and_impure_allowlist(self):
        fields = self.g.nodes['Entry']['fields']
        self.assertIn('MetaData=(bCallInEditor=True)', fields)
        self.assertIn('ExtraFlags=201457664', fields)
        self.assertIn('FunctionReference=(MemberName="' + build.FUNCTION + '")', fields)
        self.assertEqual(set(self.g.nodes['Entry']['pins']), {'then'})
        self.assertEqual(self.g.locals, {})
        self.assertNotIn('Return', self.g.nodes)
        allowed = set(build.TARGETS) | {'PrintString', 'Not_PreBool', 'EqualEqual_IntInt', 'EqualEqual_StrStr', 'BooleanAND'}
        for name, node in self.g.nodes.items():
            self.assertFalse(any(f.startswith('VariableReference=') or f.startswith('LocalVariables(') for f in node['fields']))
            if name != 'Entry' and not node['class'].endswith('.K2Node_IfThenElse'):
                self.assertIn(function(node), allowed)

    def test_all_static_logs_bounded_and_log_only(self):
        m = DriverMachine(self.g)
        for name, node in self.g.nodes.items():
            if name != 'Entry' and not node['class'].endswith('.K2Node_IfThenElse') and function(node) == 'PrintString':
                text = m.input(name, 'InString')
                self.assertTrue(text.isascii())
                self.assertLessEqual(len(text), 128)
                self.assertTrue(m.input(name, 'bPrintToLog'))
                self.assertFalse(m.input(name, 'bPrintToScreen'))
        self.assertLessEqual(sum(map(len, m.run().messages)), 1024)

    def test_exact_frozen_payload_reemit_and_reciprocal_edges(self):
        payload = (EVIDENCE / (build.FUNCTION + '.clipboard.txt')).read_bytes()
        self.assertEqual(hashlib.sha256(payload).hexdigest(), '52b70b702a1b2fa43ffd7333ff2ef88746a6d713bb18bb8155e639940347b23d')
        self.assertEqual(build.emit_entry_only(self.g), payload)
        quoted = payload.decode().split('NodesString=', 1)[1]
        body, end = json.JSONDecoder().raw_decode(quoted)
        self.assertEqual(quoted[end:], ')')
        nodes = [{'relative_path': m.group(2), 'pin_lines': [{'text': line.strip()} for line in m.group(3).split('\r\n') if line.strip().startswith('CustomProperties Pin (')]}
                 for m in re.finditer(r'Begin Object Class=([^ ]+) Name="([^"]+)"\r\n(.*?)\r\nEnd Object', body, re.S)]
        pins, edges, external = self.g.h['checked_graph'](nodes)
        self.assertEqual((len(nodes), len(pins), len(edges), external), (50, 294, 140, []))

    def test_native_defaults_and_unicode_preserved_before_import(self):
        m = DriverMachine(self.g)
        for case in self.fixtures:
            node = 'Case%02dCall' % case['case_id']
            for pin, expected in case['inputs'].items():
                self.assertEqual(m.input(node, pin), expected)
        self.assertEqual(m.input('Case04Call', 'Raw'), 'W' * 39 + '\U0001f680Z')
        self.assertEqual(m.input('Case04SegmentedEquals', 'B'), 'W' * 39 + '\n\U0001f680Z')

    def test_source_pins_and_fresh_identity_and_python37(self):
        sources = {(n['source']['path'], n['source']['sha256']) for n in self.g.nodes.values()}
        for path, sha in sources:
            self.assertEqual(hashlib.sha256(Path(path).read_bytes()).hexdigest(), sha)
        fresh = build.fixture_graph()
        self.assertFalse(set(fresh.validate()['ids']) & set(self.g.validate()['ids']))
        native_ids = set(re.findall(r'(?:NodeGuid|GraphGuid|PinId)=([A-F0-9]{32})', build.NATIVE.read_text()))
        self.assertFalse(native_ids & set(self.g.validate()['ids']))
        for path in (Path(build.__file__), Path(__file__)):
            ast.parse(path.read_text(), filename=str(path), feature_version=(3, 7))


