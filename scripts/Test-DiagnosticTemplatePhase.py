class PhaseChecks(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='mw5-phase-mock-')
        self.root = Path(self.temp.name).resolve()
        self.addCleanup(self.cleanup)
        self.base = phase.load_base()
