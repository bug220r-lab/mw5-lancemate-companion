class AdmissionChecks(PhaseChecks):
    # Do not inherit the execution tests a second time.
    pass


for _name in list(PhaseChecks.__dict__):
    if _name.startswith('test_'):
        setattr(AdmissionChecks, _name, None)


def admission_setup(self):
    PhaseChecks.setUp(self)
    self.identity = {'pid': 12345, 'creation_filetime': '134000000000000000',
                     'executable': str(self.root / 'Editor/Engine/Binaries/Win64/UE4Editor.exe')}
    self.base.EDITOR_EXE = Path(self.identity['executable'])
    self.base.EXPECTED_ROOT = self.root
    self.roots = phase.mod_roots(self.base)
    for root in self.roots:
        root.mkdir(parents=True)
        (root / 'mod.json').write_text('{"MOCK_ONLY":true}')
    self.select('stock')
    self.now = datetime.datetime.now(datetime.timezone.utc)
    self.decorate()


AdmissionChecks.setUp = admission_setup


def decorate(self):
    self.manifest.update(schema_version=1, status='REVIEWED_NATIVE_READY', editor_identity=self.identity,
        reviewed_at_utc=self.now.isoformat(), native_owner_confirmed=True, native_owner='MOCK_ONLY owner',
        owner_evidence='MOCK_ONLY ownership fixture', authorization_evidence='MOCK_ONLY authorization fixture',
        base_helper_sha256=phase.BASE_SHA, helper_sha256=self.pin(Path(phase.__file__))['sha256'],
        stock_evidence=None, selection_receipt=None)


AdmissionChecks.decorate = decorate


